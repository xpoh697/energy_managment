import os
from datetime import datetime

def append_debate(task, archi_text, skeptic_text, conclusion_text):
    path = r"g:\systemair\energy_mamagment\DEBATE.md"
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    content = f"\n## [{now}] Задача: {task}\n\n"
    content += f"### Archi\n{archi_text}\n\n"
    content += f"### Skeptic\n{skeptic_text}\n\n"
    content += f"### Заключение\n{conclusion_text}\n"
    
    if os.path.exists(path):
        with open(path, "a", encoding="utf-8") as f:
            f.write(content)
    else:
        with open(path, "w", encoding="utf-8") as f:
            f.write("# Лог дебатов\n" + content)

# Phase 1: Debate
task = "Исправить коллапс бюджета в 0 и странное поведение при лимите 0.7 vs 0.71. В планировщике пусто, хотя часы в кандидатах есть."

